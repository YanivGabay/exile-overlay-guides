"""Vendor search terms from game data (RePoE fork, https://repoe-fork.github.io/mods.min.json).
Writes poe1/search.json: each preset = list of [term, item level needed].
Usage: python3 tools/build_search.py <mods.min.json>"""
import json, sys
mods = json.load(open(sys.argv[1], encoding="utf-8"))

INFLUENCE = ("elder", "shaper", "crusader", "eyrie", "basilisk", "adjudicator")

def spawnable(v):
    """Regular affixes only: no essence-only mods, and spawnable on a non-influenced base."""
    return (v.get("domain") == "item" and v.get("generation_type") in ("prefix", "suffix")
            and not v.get("is_essence_only")
            and any(w["weight"] > 0 and not any(i in w["tag"] for i in INFLUENCE) for w in v.get("spawn_weights", [])))

def affixes(stat, gen=None, tags=None):
    out = {}
    for v in mods.values():
        if not spawnable(v) or (gen and v["generation_type"] != gen):
            continue
        if not any(s["id"] == stat for s in v.get("stats", [])):
            continue
        if tags and not any(w["tag"] in tags and w["weight"] > 0 for w in v["spawn_weights"]):
            continue
        name = v["name"].replace("'s", "")  # "Runner's" -> "Runner": also matches the apostrophe-free text
        out[name] = min(out.get(name, 999), v["required_level"])
    return sorted(out.items(), key=lambda x: x[1])

presets = {
  "ms-boots": {"label": "Movement speed boots", "terms": affixes("base_movement_velocity_+%", "prefix", {"boots"})},
  "plus1-fire": {"label": "+1 fire spell wands/sceptres", "terms": affixes("fire_spell_skill_gem_level_+", "prefix")},
  "plus1-cold": {"label": "+1 cold spell wands/sceptres", "terms": affixes("cold_spell_skill_gem_level_+", "prefix")},
  "plus1-lightning": {"label": "+1 lightning spell wands/sceptres", "terms": affixes("lightning_spell_skill_gem_level_+", "prefix")},
  "plus1-chaos": {"label": "+1 chaos spell wands/sceptres", "terms": affixes("chaos_spell_skill_gem_level_+", "prefix")},
  "plus1-physical": {"label": "+1 physical spell wands/sceptres", "terms": affixes("physical_spell_skill_gem_level_+", "prefix")},
  # Pure "% increased Physical Damage" prefixes (the hybrid accuracy ones have their own names).
  "phys-weapon": {"label": "Physical damage weapons", "terms": [t for t in affixes("local_physical_damage_+%", "prefix")
                   if not any(h in t[0] for h in ("Squire", "Journeyman", "Reaver", "Mercenary", "Champion", "Conqueror", "Emperor", "Dictator"))]},
  "recipe-bases": {"label": "Weapon recipe belts (Rustic Sash, Chain Belt)", "terms": [["Rustic Sash", 1], ["Chain Belt", 1]]},
}
# Linked sockets: the in-game search matches the "Sockets:" line, e.g. "W-W-W-W".
links = {"3-link": r"\w-\w-\w", "4-link": r"\w-\w-\w-\w", "5-link": r"(\w-){4}\w"}
out = {"source": "RePoE fork mods.min.json (game data), generated by tools/build_search.py",
       "presets": presets, "links": links, "maxLength": 250}
json.dump(out, open("poe1/search.json", "w", encoding="utf-8"), indent=1, ensure_ascii=False)
for k, v in presets.items():
    print(k, [t for t, _ in v["terms"]][:10])
